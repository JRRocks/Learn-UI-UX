// Generates src/components/mockIcons.ts: a small static subset of Lucide icons (ISC)
// usable inside mocks as <i data-icon="name"></i>. Run: node scripts/gen-mock-icons.mjs
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const NAMES = `search shopping-cart shopping-bag user house heart bell menu x arrow-left arrow-right
chevron-left chevron-right chevron-down chevron-up check star play pause settings plus minus info
triangle-alert circle-alert qr-code scan-line message-circle wallet gift map-pin calendar clock mail lock
eye eye-off share-2 bookmark download upload credit-card truck package phone camera image file-text
folder log-out trash funnel face-slightly-smiling globe sparkles zap rocket shield-check badge-check thumbs-up flame ticket percent tag
layout-grid list sliders-horizontal volume-2 wifi battery-full signal ellipsis refresh-cw circle-check circle-x
undo-2 send paperclip users chart-column trending-up trending-down euro languages moon sun store
utensils car bike plane hotel film music headphones gamepad-2 graduation-cap stethoscope pill coffee
shirt baby dog sprout landmark receipt bus train-front`.split(/\s+/).filter(Boolean);

const attr = (o) => Object.entries(o).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ');
const out = {};
const missing = [];
for (const name of NAMES) {
  const file = resolve('node_modules/lucide-react/dist/esm/icons', `${name}.mjs`);
  try {
    const mod = await import(pathToFileURL(file).href);
    out[name] = mod.__iconData.node.map(([tag, a]) => `<${tag} ${attr(a)}/>`).join('');
  } catch {
    missing.push(name);
  }
}
const body = Object.entries(out).map(([k, v]) => `  '${k}': '${v}',`).join('\n');
writeFileSync(
  'src/components/mockIcons.ts',
  `// Generated by scripts/gen-mock-icons.mjs from Lucide (ISC license, https://lucide.dev). Do not edit by hand.\n` +
    `export const MOCK_ICONS: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`${Object.keys(out).length} icons written`, missing.length ? `missing: ${missing.join(', ')}` : '');
